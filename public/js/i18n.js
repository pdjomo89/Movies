const DICTS = { en, fr };
export const LANGS = [['en', 'EN', 'English'], ['fr', 'FR', 'Français']];
export const LOCALES = { en: 'en-GB', fr: 'fr-FR' };

const initial = prefs.get('lang') ?? (/^fr/i.test(navigator.language || '') ? 'fr' : 'en');
let current = DICTS[initial] ? initial : 'en';
const listeners = new Set();

export const getLang = () => current;
export const locale = () => LOCALES[current];

export function setLang(lang) {
  if (!DICTS[lang] || lang === current) return;
  current = lang;
  prefs.set('lang', lang);
  applyDocumentLang();
  listeners.forEach((fn) => fn(lang));
}

export const onLangChange = (fn) => { listeners.add(fn); return () => listeners.delete(fn); };

export function applyDocumentLang() {
  document.documentElement.lang = current;
  document.title = t('meta.title');
}

/** Plain-text translation. Functions receive the first numeric var (for plurals). */
export function t(key, vars = {}) {
  const entry = DICTS[current][key] ?? en[key];
  if (entry === undefined) return key;
  if (typeof entry === 'function') return entry(vars.n ?? vars);
  return entry.replace(/\{(\w+)\}/g, (_, k) => (vars[k] ?? ''));
}

const escape = (s) => String(s).replace(/[&<>"']/g, (c) => ({ '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;', "'": '&#39;' })[c]);

/** Translation that keeps the dictionary's own markup (<em>, <strong>) but escapes every value. */
export function tMarkup(key, vars = {}) {
  const safe = Object.fromEntries(Object.entries(vars).map(([k, v]) => [k, typeof v === 'number' ? v : escape(v)]));
  return t(key, safe);
}
